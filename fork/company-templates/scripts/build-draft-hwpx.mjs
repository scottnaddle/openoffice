// One-shot generator for the built-in draft template.
// Run after dependencies are installed: node fork/company-templates/scripts/build-draft-hwpx.mjs
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import init, { HwpDocument } from '@rhwp/core'

const here = dirname(fileURLToPath(import.meta.url))
const require = createRequire(import.meta.url)
const wasm = join(dirname(require.resolve('@rhwp/core')), 'rhwp_bg.wasm')
await init({ module_or_path: readFileSync(wasm) })

const lines = [
  '기안문',
  '회사명 {{회사명}}',
  '부서 {{부서}}',
  '기안자 {{작성자}}',
  '기안일 {{날짜}}',
  '1. 목적',
  '기안 목적을 적습니다.',
  '2. 내용',
  '내용을 적습니다.',
  '3. 요청사항',
  '요청을 적습니다.',
]

const doc = HwpDocument.createEmpty()
doc.createBlankDocument()
lines.forEach((line, index) => {
  if (index > 0) doc.splitParagraph(0, index - 1, doc.getParagraphLength(0, index - 1))
  doc.insertText(0, index, 0, line)
})

const bytes = Buffer.from(doc.exportHwpx())
const back = new HwpDocument(bytes)
const readBack = []
for (let i = 0; i < back.getParagraphCount(0); i++) {
  readBack.push(back.getTextRange(0, i, 0, back.getParagraphLength(0, i)))
}
for (const marker of ['{{회사명}}', '{{부서}}', '{{작성자}}', '{{날짜}}']) {
  if (!readBack.some((line) => line.includes(marker))) {
    throw new Error(`exported HWPX is missing ${marker}`)
  }
}

const out = join(here, '..', 'src', 'draft-hwpx.ts')
const base64 = bytes.toString('base64')
writeFileSync(
  out,
  `// Generated by scripts/build-draft-hwpx.mjs. Do not edit the payload by hand.\nexport const DRAFT_HWPX_BASE64 =\n  '${base64}'\n`,
)
console.log(`wrote ${bytes.length} bytes`)
